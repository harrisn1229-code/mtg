// node game/test/coverage.js — compiles every card in data/seed.json (+ test/fixtures-cards.json if present)
// and writes test/coverage-report.txt with parse-coverage numbers and the unparsed lines of the deck cards.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { analyzeCard } from "../parser.js";
import { compileCard as compileWithOverrides } from "../overrides.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const seed = JSON.parse(fs.readFileSync(path.join(here, "../../data/seed.json"), "utf8"));
const fxPath = path.join(here, "fixtures-cards.json");
let fixtures = [];
if (fs.existsSync(fxPath)) {
  const fx = JSON.parse(fs.readFileSync(fxPath, "utf8"));
  fixtures = Array.isArray(fx) ? fx : Object.values(fx);
}

const all = new Map(); // key -> card
for (const [k, c] of Object.entries(seed.cards)) all.set(k, c);
fixtures.forEach((c, i) => all.set("fixture:" + (c.name || i), c));
const byName = new Map();
for (const c of all.values()) {
  byName.set(c.name, c);
  if (c.faces?.length) for (const f of c.faces) if (!byName.has(f.name)) byName.set(f.name, c);
}

// deck cards
const deckKeys = new Set();
const missing = [];
for (const d of seed.decks || []) {
  for (const e of d.entries || []) {
    if (e.set && e.cn && seed.cards[e.set + ":" + e.cn]) deckKeys.add(e.set + ":" + e.cn);
    else {
      const c = byName.get(e.name);
      if (c) deckKeys.add([...all.entries()].find(([, v]) => v === c)[0]);
      else missing.push(e.name);
    }
  }
}

function stats(keys) {
  let cards = 0, full = 0, lines = 0, parsed = 0, partial = 0;
  for (const k of keys) {
    const r = analyzeCard(all.get(k));
    cards++; lines += r.lines; parsed += r.parsed; partial += r.partial.length;
    if (r.def.unparsed.length === 0) full++;
  }
  return { cards, full, lines, parsed, partial };
}
const pct = (a, b) => (b ? ((100 * a) / b).toFixed(1) : "100.0") + "%";
const sa = stats([...all.keys()]);
const sd = stats([...deckKeys]);

let out = "";
const line = (s = "") => { out += s + "\n"; };
line("Parser coverage report (game/parser.js; generated by game/test/coverage.js)");
line("");
line(`ALL cards (seed.json + fixtures): ${sa.cards}`);
line(`  fully parsed cards : ${sa.full}/${sa.cards} = ${pct(sa.full, sa.cards)}`);
line(`  parsed ability lines: ${sa.parsed}/${sa.lines} = ${pct(sa.parsed, sa.lines)}   (of which partial/manual: ${sa.partial} lines counted as NOT parsed)`);
line(`DECK cards (unique cards in the 4 decks): ${sd.cards}${missing.length ? `   [name-only entries with no card data: ${missing.join("; ")}]` : ""}`);
line(`  fully parsed cards : ${sd.full}/${sd.cards} = ${pct(sd.full, sd.cards)}`);
line(`  parsed ability lines: ${sd.parsed}/${sd.lines} = ${pct(sd.parsed, sd.lines)}   (partial/manual lines: ${sd.partial}, counted as NOT parsed)`);
line("");
const withOv = [...deckKeys].map((k) => ({ k, c: all.get(k) }));
line("Not-fully-parsed deck cards (name: unparsed lines; [manual] = ability kept but a sub-effect is a manual{} op)");
line("-".repeat(80));
const rows = [];
for (const k of deckKeys) {
  const c = all.get(k);
  const r = analyzeCard(c);
  if (r.def.unparsed.length) rows.push({ name: c.name, r });
}
rows.sort((a, b) => a.name.localeCompare(b.name));
for (const { name, r } of rows) {
  line(name);
  for (const u of r.def.unparsed) line("    " + (r.partial.includes(u) ? "[manual] " : "") + u.replace(/\n/g, "\n      "));
}
fs.writeFileSync(path.join(here, "coverage-report.txt"), out);

// also report how many deck cards remain not-full after overrides
let ovFull = 0;
for (const k of deckKeys) { const d = compileWithOverrides(all.get(k)); if (!d.unparsed.length) ovFull++; }
console.log(`all cards : ${sa.full}/${sa.cards} fully parsed (${pct(sa.full, sa.cards)}); lines ${sa.parsed}/${sa.lines} (${pct(sa.parsed, sa.lines)})`);
console.log(`deck cards: ${sd.full}/${sd.cards} fully parsed (${pct(sd.full, sd.cards)}); lines ${sd.parsed}/${sd.lines} (${pct(sd.parsed, sd.lines)})`);
console.log(`deck cards fully parsed after overrides: ${ovFull}/${sd.cards}`);
if (process.argv.includes("-v")) console.log(out);
